'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const {applyOperations, operations} = require('../mcp/gxp_editor/canvas_operations.cjs');
const design = () => ({actionData:[{key:'g',title:'Existing action',actionType:'js',data:[{
  key:'n',elementKey:'Query',depth:[],title:'Query',paramsValue:{
    inputParams:{status:'active', filters:[{column:'isDeleted',value:0}], match:'AND', nullable:null, nested:{'a/b':{'~label':'before'}}},
    outputParams:{result:{value:'rows',code:'rows',paramTypes:'custom'}},
  },
}]}],globalVariables:[]});
const api = {
  actionByKey:(d,key) => {const group=d.actionData.find(item=>item.key===key);if(!group)throw Error('group missing');return group;},
  nodeIndex:(group,key) => {const at=group.data.findIndex(item=>item.key===key);if(at<0)throw Error('node missing');return at;},
};
const native = (d,ops) => ops.map(op=>{
  assert.equal(op.operation,'replace_params');
  const group=api.actionByKey(d,op.action_group_key),at=api.nodeIndex(group,op.target_node_key);
  group.data[at]={...group.data[at],description:'Regenerated by native',paramsValue:{inputParams:structuredClone(op.input_params),outputParams:structuredClone(op.output_params)}};
  return {operation_index:0,operation:'replace_params',affected_node_keys:[op.target_node_key]};
});
const op = (extra={}) => ({operation:'set_parameter',action_group_key:'g',target_node_key:'n',expected_element_key:'Query',
  path:'/inputParams/status',expected_old_value:'active',value:'freeze',...extra});
const apply = (d,ops,generate=native) => applyOperations(d,ops,generate,api);

test('advertises guarded parameter updates',()=>assert.ok(operations.includes('set_parameter')));
test('checked no-op parameter updates preserve the canvas without native generation',()=>{
  const d=design(),before=structuredClone(d);
  const diff=apply(d,[op({value:'active'})],()=>{throw Error('no-op must not generate');});
  assert.deepEqual(d,before);assert.equal(diff[0].no_change,true);
  assert.throws(()=>apply(d,[op({value:'active',expected_old_value:'stale'})]),error=>error.details.reason_code==='old_value_mismatch');
});
test('operation errors carry bounded identity and path without parameter data',()=>{
  const request=op({expected_old_value:'private expected data'});
  assert.throws(()=>apply(design(),[op({value:'active'}),request]),error=>{
    assert.deepEqual(Object.fromEntries(['operation_index','group_key','node_key','path','reason_code'].map(key=>[key,error.details[key]])),
      {operation_index:1,group_key:'g',node_key:'n',path:'/inputParams/status',reason_code:'old_value_mismatch'});
    assert.equal(error.details.phase,'canvas_operation');
    assert.equal(error.details.expected_shape.operation,'set_parameter');
    assert.equal(error.details.refresh_scope,'target_context');
    assert.ok(!JSON.stringify(error.details).includes('private'));return true;
  });
  assert.throws(()=>apply(design(),[op({path:'/inputParams/'+ 'x'.repeat(1000)})]),error=>error.details.path.length===256);
});
test('native row key selection survives reordered arrays and preserves all other rows',()=>{
  for(const field of ['id','key']){
    const d=design(),rows=[{[field]:'second',column:'status',value:'active'},{[field]:'first',column:'isDeleted',value:0}];
    d.actionData[0].data[0].paramsValue.inputParams.filters=structuredClone(rows);
    const request=op({operation:'set_array_item',path:'/inputParams/filters',item_key:{field,value:'second'},expected_old_value:rows[0],value:{...rows[0],value:'freeze'}});
    const diff=apply(d,[request]);assert.equal(diff[0].operation,'set_array_item');
    assert.deepEqual(d.actionData[0].data[0].paramsValue.inputParams.filters,[{...rows[0],value:'freeze'},rows[1]]);
    const next=apply(d,[{...request,expected_old_value:request.value}],()=>{throw Error('no-op must not generate');});
    assert.equal(next[0].no_change,true);
  }
});
test('native row key edits reject missing, ambiguous, unsupported and changed identities',()=>{
  const base={id:'row1',column:'status',value:'active'};
  const request=op({operation:'set_array_item',path:'/inputParams/filters',item_key:{field:'id',value:'row1'},expected_old_value:base,value:{...base,value:'freeze'}});
  const make=rows=>{const d=design();d.actionData[0].data[0].paramsValue.inputParams.filters=rows;return d;};
  for(const [rows,extra,reason] of [
    [[],{},'item_key_not_found'],[[base,base],{},'ambiguous_item_key'],[[base],{item_key:{field:'column',value:'status'}},'invalid_item_key'],
    [[base],{item_key:{field:'id',value:true}},'invalid_item_key'],[[base],{value:{...base,id:'changed'}},'item_identity_changed'],
    [[base],{expected_old_value:{...base,value:'stale'}},'old_value_mismatch'],
  ]) assert.throws(()=>apply(make(structuredClone(rows)),[{...request,...extra}]),error=>error.details.reason_code===reason);
  assert.throws(()=>apply(make([base]),[{...request,path:'/inputParams/filters/0'}]),error=>error.details.reason_code==='array_index_forbidden');
});
test('updates only one existing value, preserving every filter, output and operation payload',()=>{
  const d=design(),before=structuredClone(d),request=op(),original=structuredClone(request);
  const diff=apply(d,[request]);
  before.actionData[0].data[0].paramsValue.inputParams.status='freeze';
  assert.deepEqual(d.actionData[0].data[0].paramsValue,before.actionData[0].data[0].paramsValue);
  assert.equal(d.actionData[0].data[0].description,'Regenerated by native');
  assert.equal(diff[0].operation,'set_parameter');assert.equal(diff[0].parameter_path,request.path);
  assert.deepEqual(request,original);
});
test('sequential updates compare against the immediately preceding result',()=>{
  const d=design();const diff=apply(d,[op(),op({expected_old_value:'freeze',value:'archived'})]);
  assert.equal(d.actionData[0].data[0].paramsValue.inputParams.status,'archived');
  assert.deepEqual(diff.map(item=>item.operation_index),[0,1]);
  assert.throws(()=>apply(design(),[op(),op()]),/old value changed/);
});
test('checks target identity, uniqueness and exact old JSON type/value',()=>{
  for(const extra of [{expected_element_key:'Different'},{expected_old_value:'missing'},{expected_old_value:1},{expected_old_value:true}]) {
    const d=design(),before=structuredClone(d);assert.throws(()=>apply(d,[op(extra)]),/type changed|old value changed/);assert.deepEqual(d,before);
  }
  const d=design();d.actionData[0].data.push(structuredClone(d.actionData[0].data[0]));assert.throws(()=>apply(d,[op()]),/unambiguous/);
  const duplicate=design();duplicate.actionData.push(structuredClone(duplicate.actionData[0]));assert.throws(()=>apply(duplicate,[op()]),/unambiguous/);
  assert.throws(()=>apply(design(),[op({target_node_key:'missing'})]),/unambiguous/);
  assert.throws(()=>apply(design(),[op({action_group_key:'missing'})]),/group missing/);
  assert.throws(()=>apply(design(),[op({path:'/inputParams/nullable',expected_old_value:false,value:true})]),/old value changed/);
  assert.throws(()=>apply(design(),[op({path:'/inputParams/filters',expected_old_value:[{column:'isDeleted',value:false}],value:[]})]),/old value changed/);
});
test('permits explicit null old values but requires both value fields',()=>{
  const d=design();apply(d,[op({path:'/inputParams/nullable',expected_old_value:null,value:'set'})]);
  assert.equal(d.actionData[0].data[0].paramsValue.inputParams.nullable,'set');
  for(const field of ['value','expected_old_value']){const request=op();delete request[field];assert.throws(()=>apply(design(),[request]),/requires/);}
});
test('replaces a whole array with a full old-value precondition and preserves other dictionaries',()=>{
  const d=design(),filters=structuredClone(d.actionData[0].data[0].paramsValue.inputParams.filters),outputs=structuredClone(d.actionData[0].data[0].paramsValue.outputParams);
  const next=[...filters,{column:'status',value:'freeze'}];apply(d,[op({path:'/inputParams/filters',expected_old_value:filters,value:next})]);
  assert.deepEqual(d.actionData[0].data[0].paramsValue.inputParams.filters,next);
  assert.deepEqual(d.actionData[0].data[0].paramsValue.outputParams,outputs);
  assert.throws(()=>apply(design(),[op({path:'/inputParams/filters/0/value',expected_old_value:0,value:1})]),/Array indexes/);
  assert.throws(()=>apply(design(),[op({path:'/inputParams/filters/01',expected_old_value:0,value:1})]),/Array indexes/);
});
test('accepts escaped JSON pointer names and object-key order differences',()=>{
  const d=design();apply(d,[op({path:'/inputParams/nested/a~1b/~0label',expected_old_value:'before',value:'after'})]);
  assert.equal(d.actionData[0].data[0].paramsValue.inputParams.nested['a/b']['~label'],'after');
  const old=d.actionData[0].data[0].paramsValue.outputParams.result;
  apply(d,[op({path:'/outputParams/result',expected_old_value:{paramTypes:old.paramTypes,code:old.code,value:old.value},value:{...old,value:'other',code:'other'}})]);
  assert.equal(d.actionData[0].data[0].paramsValue.outputParams.result.code,'other');
});
test('rejects roots, new keys, malformed paths and prototype pollution',()=>{
  for(const path of ['', '/', '/inputParams','/outputParams','/title','/inputParams/missing','/inputParams/nested/absent','/inputParams/bad~2','/inputParams/__proto__/x','/inputParams/constructor','/outputParams/prototype']) {
    assert.throws(()=>apply(design(),[op({path})]),/path|JSON pointer|existing|Unsafe|nonblank/);
  }
  const malicious=JSON.parse('{"__proto__":{"polluted":true}}');
  assert.throws(()=>apply(design(),[op({value:malicious})]),/Unsafe parameter key/);
  assert.equal({}.polluted,undefined);
});
test('record replacements cannot add/remove keys or swap container types',()=>{
  const old=design().actionData[0].data[0].paramsValue.outputParams.result;
  for(const value of [{...old,newField:true},{value:'rows'},[],null]) {
    assert.throws(()=>apply(design(),[op({path:'/outputParams/result',expected_old_value:old,value})]),/preserve existing keys/);
  }
  assert.throws(()=>apply(design(),[op({value:{code:'x'}})]),/scalar parameter/);
});
test('native changes to unrelated parameters fail without changing the input canvas',()=>{
  const d=design(),before=structuredClone(d);
  assert.throws(()=>apply(d,[op()],(candidate,ops)=>{const result=native(candidate,ops);candidate.actionData[0].data[0].paramsValue.inputParams.match='OR';return result;}),error=>{
    assert.match(error.message,/outside the requested value/);
    assert.deepEqual(error.details.diff_paths,['/paramsValue/inputParams/match']);
    assert.equal(error.details.diff_paths_truncated,false);return true;
  });
  assert.deepEqual(d,before);
});
test('native omission of an empty unused parameter section is equivalent',()=>{
  const d=design();d.actionData[0].data[0].paramsValue.outputParams={};
  apply(d,[op()],(candidate,ops)=>{const result=native(candidate,ops);delete candidate.actionData[0].data[0].paramsValue.outputParams;return result;});
  assert.equal(d.actionData[0].data[0].paramsValue.inputParams.status,'freeze');
});
test('known custom ParamInput requires a complete synchronized record',()=>{
  const d=design(),node=d.actionData[0].data[0];node.elementKey='SetVariable';
  node.paramsValue.inputParams.variableValue={paramTypes:'custom',value:'1',code:'1',label:'1'};
  const request=op({expected_element_key:'SetVariable',path:'/inputParams/variableValue/value',expected_old_value:'1',value:'2'});
  assert.throws(()=>apply(d,[request]),/complete ParamInput/);
  const record=structuredClone(node.paramsValue.inputParams.variableValue);
  assert.throws(()=>apply(d,[{...request,path:'/inputParams/variableValue',expected_old_value:record,value:{...record,value:'2'}}]),/synchronized/);
  apply(d,[{...request,path:'/inputParams/variableValue',expected_old_value:record,value:{...record,value:'2',code:'2'}}]);
  assert.equal(d.actionData[0].data[0].paramsValue.inputParams.variableValue.code,'2');
  const stale=design(),bad={...record,code:'different'};stale.actionData[0].data[0].elementKey='SetVariable';
  stale.actionData[0].data[0].paramsValue.inputParams.variableValue=bad;
  apply(stale,[{...request,path:'/inputParams/variableValue',expected_old_value:bad,value:{...record,value:'3',code:'3'}}]);
  assert.equal(stale.actionData[0].data[0].paramsValue.inputParams.variableValue.code,'3');
});
test('known property ParamInput and variable output follow the same synchronized-record rule',()=>{
  for(const [element,section,name] of [['SetVariableValue','inputParams','attributeValue'],['SetVariable','outputParams','variableName']]) {
    const d=design(),node=d.actionData[0].data[0];node.elementKey=element;
    const record={paramTypes:'custom',value:'before',code:'before'};node.paramsValue[section][name]=record;
    assert.throws(()=>apply(d,[op({expected_element_key:element,path:`/${section}/${name}/code`,expected_old_value:'before',value:'after'})]),/complete ParamInput/);
    apply(d,[op({expected_element_key:element,path:`/${section}/${name}`,expected_old_value:record,value:{...record,value:'after',code:'after'}})]);
  }
});
